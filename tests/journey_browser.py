import json, pathlib, tempfile, threading, http.server, functools
from playwright.sync_api import sync_playwright
ROOT=pathlib.Path(__file__).resolve().parents[1]
server=http.server.ThreadingHTTPServer(("127.0.0.1",0),functools.partial(http.server.SimpleHTTPRequestHandler,directory=str(ROOT)))
threading.Thread(target=server.serve_forever,daemon=True).start()
url=f"http://127.0.0.1:{server.server_port}/jornada.html"
passed=[]
def check(name,cond):
    assert cond,name
    passed.append(name)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    context=browser.new_context(viewport={"width":1280,"height":900},accept_downloads=True)
    page=context.new_page()
    errors=[]
    page.on("pageerror",lambda e:errors.append(str(e)))
    page.goto(url)
    page.evaluate("""localStorage.clear();localStorage.setItem('genesis.journey.v1',JSON.stringify({version:1,lang:'pt',days:5,perDay:3,units:{V01:{stage:1,hours:2}},projects:{}}))""")
    page.reload()
    check("legacy migration",page.locator("#logged").inner_text()=="2 h 0 min")
    page.locator("#session-unit").select_option("V01")
    page.locator("#session-start").fill("2025-01-01T10:00")
    page.locator("#session-end").fill("2025-01-01T11:00")
    page.locator("#session-form button").click()
    check("session counted once",page.locator("#logged").inner_text()=="3 h 0 min")
    page.locator("#session-unit").select_option("V02")
    page.locator("#session-form button").click()
    check("cross-unit overlap refused","sobreposta" in page.locator("#journal-status").inner_text() and page.locator("#logged").inner_text()=="3 h 0 min")
    page.locator("#evidence-title").fill("<img src=x onerror=alert(1)>")
    page.locator("#evidence-form button").click()
    check("evidence text safe",page.locator("#evidence-list img").count()==0 and "<img" in page.locator("#evidence-list").inner_text())
    check("evidence no hours",page.locator("#logged").inner_text()=="3 h 0 min")
    page.reload()
    check("persistence",page.locator("#logged").inner_text()=="3 h 0 min" and page.locator("#evidence-list article").count()==1)
    with tempfile.TemporaryDirectory() as d:
        path=pathlib.Path(d)/"backup.json"
        with page.expect_download() as dl:page.locator("#export").click()
        dl.value.save_as(path)
        saved=json.loads(path.read_text())
        check("export v4",saved["version"]==4 and len(saved["sessions"])==1)
        page.once("dialog",lambda d:d.accept())
        page.locator("#reset").click()
        check("reset",page.locator("#logged").inner_text()=="0 h 0 min")
        page.once("dialog",lambda d:d.accept())
        page.locator("#import").set_input_files(str(path))
        page.wait_for_function("document.querySelector('#logged').textContent==='3 h 0 min'")
        check("restore",page.locator("#evidence-list article").count()==1)
        bad=pathlib.Path(d)/"bad.json";bad.write_text('{"version":2}')
        page.locator("#import").set_input_files(str(bad))
        page.wait_for_function("document.querySelector('#storage').textContent.includes('inválido')")
        check("invalid backup preserves state",page.locator("#logged").inner_text()=="3 h 0 min")
    page.once("dialog",lambda d:d.accept())
    page.locator("#session-list article button").click()
    check("delete session updates hours and status",page.locator("#logged").inner_text()=="2 h 0 min" and "excluído" in page.locator("#journal-status").inner_text())
    page.once("dialog",lambda d:d.accept())
    page.locator("#evidence-list article button").click()
    check("delete evidence leaves hours unchanged",page.locator("#logged").inner_text()=="2 h 0 min" and "excluído" in page.locator("#evidence-status").inner_text())
    page.locator("#goal-minutes").fill("300")
    page.locator("#goal-reviews").fill("2")
    page.locator("#goal-form button").click()
    check("weekly goals",page.locator("#week-time").inner_text()=="0 / 300" and page.locator("#week-review").inner_text()=="0 / 2")
    page.locator("#review-unit").select_option("V07")
    page.locator("#review-rating").select_option("good")
    page.locator("#review-form button").click()
    check("review recorded",page.locator("#week-review").inner_text()=="1 / 2" and page.locator("#scheduled-count").inner_text()=="1")
    check("review no extra time",page.locator("#logged").inner_text()=="2 h 0 min")
    page.locator("#review-form button").click()
    check("duplicate review refused","já registrada" in page.locator("#review-status").inner_text())
    page.reload()
    check("goal and review persistence",page.locator("#week-review").inner_text()=="1 / 2")
    page.locator("#diag-unit").select_option("V12")
    before=page.locator('#diag-form input[name="diagnostic-0"]').evaluate_all("(els)=>els.map(e=>e.value)")
    for i,value in enumerate([1,0,2]):
        page.locator(f'#diag-form input[name="diagnostic-{i}"][value="{value}"]').check()
    page.locator("#diag-form button").click()
    check("diagnostic scored",page.locator("#diag-total").inner_text()=="3/3" and page.locator("#diag-covered").inner_text()=="1/10")
    check("diagnostic feedback","Último resultado: 3/3" in page.locator("#diag-feedback").inner_text())
    after=page.locator('#diag-form input[name="diagnostic-0"]').evaluate_all("(els)=>els.map(e=>e.value)")
    check("alternative order changes",before!=after and sorted(before)==sorted(after))
    check("diagnostic no hours",page.locator("#logged").inner_text()=="2 h 0 min")
    for i,value in enumerate([0,1,0]):
        page.locator(f'#diag-form input[name="diagnostic-{i}"][value="{value}"]').check()
    page.locator("#diag-form button").click()
    check("latest and best",page.locator("#diag-total").inner_text()=="0/3" and "Melhor: 3/3" in page.locator("#competency-list").inner_text())
    page.reload()
    check("diagnostic persistence",page.locator("#diag-attempts").inner_text()=="2" and page.locator("#diag-total").inner_text()=="0/3")
    with tempfile.TemporaryDirectory() as d:
        path=pathlib.Path(d)/"diagnostic.json"
        with page.expect_download() as dl:page.locator("#export").click()
        dl.value.save_as(path)
        saved=json.loads(path.read_text())
        check("diagnostic backup contents",len(saved["attempts"])==2 and saved["version"]==4)
        page.once("dialog",lambda d:d.accept())
        page.locator("#reset").click()
        page.once("dialog",lambda d:d.accept())
        page.locator("#import").set_input_files(str(path))
        page.wait_for_function("document.querySelector('#diag-attempts').textContent==='2'")
        check("diagnostic restore",page.locator("#diag-total").inner_text()=="0/3" and page.locator("#logged").inner_text()=="2 h 0 min")
    page.locator("#diag-unit").select_option("V21")
    for i,value in enumerate([0,1,2]):
        page.locator(f'#diag-form input[name="diagnostic-{i}"][value="{value}"]').check()
    page.locator("#diag-form button").click()
    check("new security diagnostic",page.locator("#diag-covered").inner_text()=="2/10" and page.locator("#diag-total").inner_text()=="3/6")
    check("new diagnostic no extra hours",page.locator("#logged").inner_text()=="2 h 0 min")
    page.reload()
    check("new diagnostic persists",page.locator("#diag-attempts").inner_text()=="3")
    page.locator("#en").click()
    check("English",page.locator("html").get_attribute("lang")=="en" and page.locator("#journal-heading").inner_text()=="Study journal")
    page.locator("#pt").click()
    page.locator("#search").fill("V01")
    check("search",page.locator("#count").inner_text()=="1 disciplinas exibidas")
    check("hours read-only",page.locator("[data-unit-hours] input").count()==0)
    page.locator("#search").fill("")
    page.set_viewport_size({"width":360,"height":800})
    print("mobile overflow candidates",page.evaluate("""[...document.querySelectorAll("body *")].filter(e=>e.getBoundingClientRect().right>innerWidth+1).slice(0,10).map(e=>[e.tagName,e.id,e.className])"""),flush=True)
    check("mobile horizontal layout",page.evaluate("document.documentElement.scrollWidth<=innerWidth"))
    for w in [320,768,1280]:
        page.set_viewport_size({"width":w,"height":800})
        check("reflow "+str(w),page.evaluate("document.documentElement.scrollWidth<=innerWidth"))
    check("labels",page.evaluate("""Array.from(document.querySelectorAll('input,select')).every(e=>e.labels?.length||e.hasAttribute('aria-label'))"""))
    check("unique ids",page.evaluate("""new Set([...document.querySelectorAll('[id]')].map(e=>e.id)).size===document.querySelectorAll('[id]').length"""))
    page.locator("body").click(position={"x":1,"y":1})
    page.keyboard.press("Tab")
    check("keyboard focus",page.evaluate("document.activeElement!==document.body"))
    check("no JS errors",not errors)
    browser.close()
server.shutdown()
print(json.dumps({"passed":len(passed),"checks":passed},ensure_ascii=False))
